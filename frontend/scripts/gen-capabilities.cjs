/* eslint-disable @typescript-eslint/no-require-imports -- CommonJS build script */
'use strict'

const fs = require('fs')
const path = require('path')

const manifestPath = path.join(__dirname, '..', '..', 'core', 'capabilities', 'protocols.json')
const outputPath = path.join(__dirname, '..', 'src', 'types', 'capabilities.ts')

function loadManifest() {
  const manifest = JSON.parse(fs.readFileSync(manifestPath, 'utf8'))
  for (const category of ['inbounds', 'outbounds', 'groups', 'endpoints', 'services']) {
    if (!Array.isArray(manifest[category])) {
      throw new Error(`protocols.json: missing ${category} array`)
    }
  }
  return manifest
}

function quoteList(values) {
  return `[${values.map((value) => JSON.stringify(value)).join(', ')}] as const`
}

function render(manifest) {
  const inbounds = manifest.inbounds.filter((inbound) => !inbound.alias)
  const pickInbound = (predicate) => inbounds.filter(predicate).map((inbound) => inbound.type)
  const simple = (category) => manifest[category].map(({ type, buildTag = '' }) => ({ type, buildTag }))
  return (
    '// GENERATED by scripts/gen-capabilities.cjs. Do not edit by hand.\n' +
    '// Source: core/capabilities/protocols.json.\n\n' +
    `export const inboundTypes = ${quoteList(inbounds.map((inbound) => inbound.type))}\n` +
    `export const inboundWithUsers = ${quoteList(pickInbound((inbound) => inbound.hasUsers))}\n` +
    `export const HasInData = ${quoteList(pickInbound((inbound) => inbound.hasInData))}\n` +
    `export const HasTls = ${quoteList(pickInbound((inbound) => inbound.hasTlsTemplate))}\n` +
    `export const MuxAvailable = ${quoteList(pickInbound((inbound) => inbound.muxAvailable))}\n` +
    `export const OnlyTLS = ${quoteList(pickInbound((inbound) => inbound.onlyTls))}\n` +
    `export const inboundEditors = ${JSON.stringify(Object.fromEntries(inbounds.map((inbound) => [inbound.type, inbound.uiEditor])), null, 2)} as const\n` +
    `export const outboundCapabilities = ${JSON.stringify(simple('outbounds'), null, 2)} as const\n` +
    `export const endpointCapabilities = ${JSON.stringify(simple('endpoints'), null, 2)} as const\n` +
    `export const serviceCapabilities = ${JSON.stringify(simple('services'), null, 2)} as const\n` +
    `export const outboundGroupCapabilities = ${JSON.stringify(manifest.groups, null, 2)} as const\n`
  )
}

function main() {
  const generated = render(loadManifest())
  if (process.argv.includes('--check')) {
    let current = ''
    try {
      current = fs.readFileSync(outputPath, 'utf8')
    } catch {
      // A missing output is drift.
    }
    if (current !== generated) {
      console.error('ERROR: frontend capability projection is out of date; run npm run gen:capabilities')
      process.exit(1)
    }
    console.log('frontend capability projection is in sync')
    return
  }
  fs.writeFileSync(outputPath, generated)
}

main()
